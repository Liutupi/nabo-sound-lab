class Art:
    def __init__(self, name, width, height, meaning):
        self.name, self.w, self.h, self.meaning = name, width, height, meaning
        self.im = Image.new('RGBA', (width * 4, height * 4))
        self.d = ImageDraw.Draw(self.im)
        self.svg = []

    def _a(self, fill, stroke=None, sw=1):
        return f'fill="{fill or "none"}" stroke="{stroke or "none"}" stroke-width="{sw}" stroke-linejoin="round" stroke-linecap="round"'

    def rect(self, xy, fill, stroke=None, sw=1, radius=0):
        x0, y0, x1, y1 = xy
        box = tuple(round(v * 4) for v in xy)
        if radius:
            self.d.rounded_rectangle(box, radius=round(radius*4), fill=fill, outline=stroke, width=round(sw*4))
        else:
            self.d.rectangle(box, fill=fill, outline=stroke, width=round(sw*4))
        self.svg.append(f'<rect x="{x0}" y="{y0}" width="{x1-x0}" height="{y1-y0}" rx="{radius}" {self._a(fill, stroke, sw)}/>')

    def poly(self, points, fill, stroke=DARK, sw=1):
        pts = [(round(x*4), round(y*4)) for x,y in points]
        self.d.polygon(pts, fill=fill)
        if stroke:
            self.d.line(pts+[pts[0]], fill=stroke, width=round(sw*4), joint='curve')
        p = ' '.join(f'{x},{y}' for x,y in points)
        self.svg.append(f'<polygon points="{p}" {self._a(fill, stroke, sw)}/>')

    def ellipse(self, xy, fill, stroke=None, sw=1):
        x0,y0,x1,y1=xy
        self.d.ellipse(tuple(round(v*4) for v in xy), fill=fill, outline=stroke, width=round(sw*4))
        self.svg.append(f'<ellipse cx="{(x0+x1)/2}" cy="{(y0+y1)/2}" rx="{(x1-x0)/2}" ry="{(y1-y0)/2}" {self._a(fill,stroke,sw)}/>')

    def line(self, points, fill, sw=1):
        pts=[(round(x*4),round(y*4)) for x,y in points]
        self.d.line(pts, fill=fill, width=max(1,round(sw*4)), joint='curve')
        p=' '.join(f'{x},{y}' for x,y in points)
        self.svg.append(f'<polyline points="{p}" {self._a(None,fill,sw)}/>')

    def ring(self, xy, color, sw=1):
        self.ellipse(xy, None, color, sw)

    def save(self):
        # The 4x master is the drawing source; nearest sampling preserves the
        # native hard outline. It also avoids partially transparent RGB565 edges.
        native=self.im.resize((self.w,self.h),Image.Resampling.NEAREST)
        self.im.save(HERE/f'{self.name}-4x.png')
        native.save(HERE/f'{self.name}.png')
        svg=f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" height="{self.h}" viewBox="0 0 {self.w} {self.h}">\n'+'\n'.join(self.svg)+'\n</svg>\n'
        (SOURCES/f'{self.name}.svg').write_text(svg,encoding='utf-8')
        assets.append(dict(name=self.name,dimensions=[self.w,self.h],meaning=self.meaning))


def new(name, meaning):
    return Art(name,16,16,meaning)


