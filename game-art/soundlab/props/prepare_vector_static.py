def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

for item in assets:
    name=item['name']
    item['files']={}
    for suffix in ['', '-4x']:
        p=HERE/f'{name}{suffix}.png'
        im=Image.open(p)
        item['files'][p.name]={'dimensions':list(im.size),'mode':im.mode,'sha256':sha(p)}
    p=SOURCES/f'{name}.svg'
    item['source']={'path':str(p.relative_to(HERE)).replace('\\','/'),'sha256':sha(p)}

